            t = time.time()
            try:
                r = A.ask(q)
                ans, err = r["answer"], None
            except Exception as e:      # noqa: BLE001
                ans, err, r = "", repr(e), {}
            row = {"faq": fid, "q": q, "kind": kind, "keys": keys, "src_expected": src, "answer": ans,
                   "auto": "오류" if err else auto_score(ans, keys, kind), "error": err,
                   "hits": r.get("hits"),
                   "unsupported_numbers": r.get("unsupported_numbers"), "sec": round(time.time() - t, 1)}
            rows.append(row)
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            f.flush()
