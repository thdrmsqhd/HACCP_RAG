NEG_OK = re.compile(r"근거에\s*(?:없|명시|나와 있지|포함되어 있지)|확인할 수 없|찾을 수 없|답변할 수 없|알 수 없|제공(?:된|하는) 자료에 없")
NEG_BAD = re.compile(r"\d+\s*(?:일|원|천원|만원)")   # 근거 없이 지어낸 기간·금액


def norm(s):
    return re.sub(r"\s+", "", s)


def auto_score(answer, keys, kind):
    if kind == "neg":
        return "정답" if NEG_OK.search(answer) and not NEG_BAD.search(answer) else "확인필요"
    hit = [any(norm(a) in norm(answer) for a in k.split("|")) for k in keys]
    return "정답" if all(hit) else ("부분" if any(hit) else "오답")


